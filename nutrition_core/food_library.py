"""Curated reference food library - ~500 ingredients, per-100g values.

Nutrient values follow standard reference data (USDA FoodData Central style
composition tables and Israeli manufacturer label values for local staples),
all normalized to 100 g of edible portion. These rows are REFERENCE data
(`evidence="reference-data"`, `verified=1`), not synthetic fixtures: the
coach still governs what may be served through rules/targets, but a trainee
request that names a library food can be composed deterministically instead
of falling back to an external lookup.

Design notes:
- All nutrients are per `basis_g` = 100 g. None = unknown, never zero.
- `allergens` uses the platform vocabulary: milk, gluten, egg, peanut, nuts,
  soy, fish, sesame, shellfish, sulfites.
- Generic one-word aliases (e.g. "אורז") live on exactly ONE canonical row so
  exact-alias matching stays unambiguous; other rows get specific aliases.
- `kind` is a coarse basket label only - no rule logic reads it.
"""
