_ANIMAL_KINDS = {"meat", "poultry", "fish", "seafood", "egg", "dairy"}
_ANIMAL_ALLERGENS = {"milk", "egg", "fish", "shellfish"}
_MEAT_KINDS = {"meat", "poultry"}
_MEAT_ALLERGENS: set = set()


def _derive_attributes(row: dict) -> List[str]:
    """Dietary flags derived deterministically from the row's own data:
    allergen set, kind, and nutrient values. Never hand-maintained - if the
    nutrients change, the flags change with them. A coach rule can require
    any of these via require_verified_attribute/diet_flag."""
    attrs = set()
    allergens = None if row["allergens"] is None else set(row["allergens"])
    kind = row["kind"]
    n = row["nutrients"]

    # Fail-closed: when the allergen set is unknown (None), no claim that
    # requires it (vegan/vegetarian/allergen-free flags) may be emitted.
    # kind alone can only block claims, never prove them.
    if allergens is not None:
        animal = kind in _ANIMAL_KINDS or bool(allergens & _ANIMAL_ALLERGENS)
        if not animal:
            attrs.add("vegan")
            attrs.add("vegetarian")
        elif kind in _MEAT_KINDS or allergens & {"fish", "shellfish"}:
            pass  # meat/fish - neither vegetarian nor vegan
        else:
            attrs.add("vegetarian")
        if "milk" not in allergens and kind != "dairy":
            attrs.add("lactose_free")
            attrs.add("dairy_free")
        if "gluten" not in allergens:
            attrs.add("gluten_free")

    def _g(key):
        v = n.get(key)
        return float(v) if v is not None else None

    sugar, sodium = _g("sugar_g"), _g("sodium_mg")
    fat, protein, fiber, carbs = _g("fat_g"), _g("protein_g"), _g("fiber_g"), _g("carbs_g")
    if sugar is not None:
        if sugar < 5:
            attrs.add("low_sugar")
        elif sugar > 15:
            attrs.add("high_sugar")
    if sodium is not None:
        if sodium < 120:
            attrs.add("low_sodium")
        elif sodium > 600:
            attrs.add("high_sodium")
    if fat is not None:
        if fat < 3:
            attrs.add("low_fat")
        elif fat > 17.5:
            attrs.add("high_fat")
    if protein is not None and protein > 10:
        attrs.add("high_protein")
    if fiber is not None and fiber > 6:
        attrs.add("high_fiber")
    if carbs is not None and carbs < 10:
        attrs.add("low_carb")
    kosher = _kosher_class(row)
    if kosher:
        attrs.add(kosher)
    return sorted(attrs)


# every flag _derive_attributes can emit - the vocabulary a coach/profile
# may require via a diet_flag rule. Unknown flags must never reach the
# engine (they would silently fail every food).
KNOWN_DIET_FLAGS = {
    "vegan", "vegetarian", "lactose_free", "dairy_free", "gluten_free",
    "low_sugar", "high_sugar", "low_sodium", "high_sodium", "low_fat",
    "high_fat", "high_protein", "high_fiber", "low_carb",
    "parve", "dairy", "meat", "non_kosher",
}


def derive_attributes(name_he: str, kind: str,
                      allergens: Optional[List[str]],
                      nutrients: dict) -> List[str]:
    """Public version for foods added at runtime (coach/manual insert):
    computes the same deterministic flags from the same inputs.
    allergens=None means UNKNOWN - allergen-based claims are suppressed."""
    return _derive_attributes({
        "name_he": name_he, "kind": kind,
        "allergens": None if allergens is None else list(allergens),
        "nutrients": nutrients,
    })


def _kosher_class(row: dict) -> Optional[str]:
    """Kashrut class derived from kind/allergens - parve / dairy / meat /
    non_kosher. The class is a fact of the ingredient, not a certification
    claim; strict-kashrut rules still require 'certified', which reference
    data never claims. Returns None when the allergen set is unknown and
    kind alone cannot decide the class."""
    allergens = None if row["allergens"] is None else set(row["allergens"])
    kind = row["kind"]
    if kind == "seafood" or (allergens is not None and "shellfish" in allergens):
        return "non_kosher"
